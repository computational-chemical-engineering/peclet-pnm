"""Contract: the shipped type stub packaging/_pnm.pyi covers every public name of peclet.pnm._pnm.

The stub is generated by nanobind.stubgen against an MPI-enabled host build (recipe in
CMakeLists.txt, next to the rule that stages it). A binding added without regenerating it fails
here. Names in the stub but absent at runtime fail too, except on a build without MPI, which lacks
the distributed names the stub carries.

Run: PYTHONPATH=<build> python -m pytest -q tests/python/test_stub_sync.py
"""
import ast
from pathlib import Path

from peclet.pnm import _pnm

STUB = Path(__file__).resolve().parents[2] / "packaging" / "_pnm.pyi"
# Bound only under PECLET_PNM_MPI (src/pnm_bindings.cpp).
MPI_ONLY = {"mpi_block", "extract_pore_network_mpi", "extract_network_flow_mpi"}


def _public(name):
    return not name.startswith("_") or name == "__init__"


def _members(cls):
    return {f"{cls.name}.{m.name}" for m in cls.body
            if isinstance(m, ast.FunctionDef) and _public(m.name)}


def _stub_names():
    names = set()
    for node in ast.parse(STUB.read_text()).body:
        if isinstance(node, ast.ClassDef):
            names |= {node.name} | _members(node)
        elif isinstance(node, ast.FunctionDef):
            names.add(node.name)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return names


def _runtime_names():
    names = set()
    for name in dir(_pnm):
        if name.startswith("_"):
            continue
        names.add(name)
        obj = getattr(_pnm, name)
        if isinstance(obj, type):
            # A class without a bound constructor (SDFReader) still has nanobind's refusing
            # __init__, which carries no signature and is not part of the API.
            names.update(f"{name}.{m}" for m, v in vars(obj).items()
                         if _public(m) and (m != "__init__" or hasattr(v, "__nb_signature__")))
    return names


def test_stub_covers_every_public_name():
    missing = sorted(_runtime_names() - _stub_names())
    assert not missing, (f"public names of peclet.pnm._pnm missing from {STUB.name}: {missing}; "
                         "regenerate the stub (recipe in CMakeLists.txt)")


def test_stub_names_exist_at_runtime():
    extra = _stub_names() - _runtime_names()
    if not hasattr(_pnm, "mpi_block"):  # a build without MPI: the stub lists more
        extra -= MPI_ONLY
    assert not extra, f"names in {STUB.name} that peclet.pnm._pnm does not define: {sorted(extra)}"
